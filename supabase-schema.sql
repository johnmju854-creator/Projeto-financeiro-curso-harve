-- supabase-schema.sql — tabelas da Caderneta da Claudia (para o SUPABASE)
--
-- COMO USAR (nesta ordem):
--   1) Supabase > SQL Editor > New query > cole ESTE arquivo inteiro > Run
--   2) Depois cole e rode o rls-supabase.sql  (liga a protecao: cada pessoa so ve os proprios dados)
--   3) (Opcional) rode o supabase-dados-exemplo.sql para ter algo na tela
--
-- Tudo roda dentro de uma transacao: se algo der erro, NADA e criado e voce pode tentar de novo.
-- Pode rodar mais de uma vez sem problema (usa "if not exists").

begin;

-- 1) CATEGORIAS: cada pessoa tem as suas (Mercado, Salario, ...) ---------------------------
create table if not exists public.categorias (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nome       text not null check (length(btrim(nome)) > 0),
  tipo       text not null default 'saida' check (tipo in ('entrada', 'saida')),
  cor        text not null default '#9E9E9E' check (cor ~ '^#[0-9A-Fa-f]{6}$'),
  criado_em  timestamptz not null default now()
);
-- (Banco ja criado ANTES de existirem tipo e cor? Rode o supabase-categorias-tipo-cor.sql.)
-- Nao deixa a mesma pessoa ter duas categorias com o mesmo nome ("Lazer" e "lazer ")
create unique index if not exists categorias_user_nome_uniq
  on public.categorias (user_id, lower(btrim(nome)));

-- 2) CONTAS: corrente, cartao, carteira (especie) e poupanca -------------------------------
create table if not exists public.contas (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nome           text not null check (length(btrim(nome)) > 0),
  tipo           text not null default 'corrente'
                 check (tipo in ('corrente', 'cartao', 'especie', 'poupanca')),
  saldo_inicial  numeric(12,2) not null default 0,
  criado_em      timestamptz not null default now()
);

-- 3) LANCAMENTOS: cada entrada ou saida de dinheiro ---------------------------------------
create table if not exists public.lancamentos (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- nao deixa apagar uma conta que ainda tem lancamentos (evita perder dados sem querer)
  conta_id         bigint not null references public.contas (id) on delete restrict,
  -- categoria e OPCIONAL; se a categoria for apagada, o lancamento fica "sem categoria"
  categoria_id     bigint references public.categorias (id) on delete set null,
  tipo             text not null check (tipo in ('entrada', 'saida')),
  valor            numeric(12,2) not null check (valor > 0),
  data_lancamento  date not null,
  descricao        text check (descricao is null or length(descricao) <= 200),
  criado_em        timestamptz not null default now()
);

-- 4) INDICES: deixam as consultas rapidas (o app sempre filtra por user_id) ---------------
create index if not exists idx_categorias_user      on public.categorias (user_id);
create index if not exists idx_contas_user          on public.contas (user_id);
create index if not exists idx_lancamentos_user_data on public.lancamentos (user_id, data_lancamento desc);
create index if not exists idx_lancamentos_conta     on public.lancamentos (conta_id);
create index if not exists idx_lancamentos_categoria on public.lancamentos (categoria_id);

-- 5) PERMISSOES -----------------------------------------------------------------------------
-- Quem esta LOGADO (authenticated) pode usar as tabelas (o RLS do proximo arquivo limita a
-- linhas proprias). Quem NAO esta logado (anon, a chave publishable sem login) nao pode nada.
grant select, insert, update, delete
  on public.categorias, public.contas, public.lancamentos to authenticated;
revoke all
  on public.categorias, public.contas, public.lancamentos from anon;

-- 6) Avisa a API do Supabase que as tabelas novas existem (senao ela demora a enxergar)
notify pgrst, 'reload schema';

commit;

